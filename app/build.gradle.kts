val sherpaVersion = "2.0.3"
val sherpaAarFile = layout.projectDirectory.file("libs/sherpa-onnx-$sherpaVersion.aar").asFile

val downloadSherpaOnnxAar by tasks.registering {
    outputs.file(sherpaAarFile)
    doLast {
        if (!sherpaAarFile.exists()) {
            sherpaAarFile.parentFile.mkdirs()
            val url = "https://github.com/k2-fsa/sherpa-onnx/releases/download/v$sherpaVersion/sherpa-onnx-$sherpaVersion.aar"
            logger.lifecycle("Downloading $url ...")
            URI(url).toURL().openStream().use { input ->
                sherpaAarFile.outputStream().use { output ->
                    input.copyTo(output)
                }
            }
        }
    }
}

tasks.named("preBuild") {
    dependsOn(downloadSherpaOnnxAar)
}

